def greet(name): # Here name is a parameter 
    print("Good Morning",name)

greet("Harry")# here you are assigning a value to the parameter name 

def greet(name,end): #  you can add parameters by using ','
    print("Good Morning",name)
    print(end)

greet("Harry","Thank You")
greet("Divya","Thanks")
greet("Rahul","Thank You")