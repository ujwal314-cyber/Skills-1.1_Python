print("Harry is a good boy \nbut not a bad boy")# \n moves the string after it to the next line
print("Harry is a good boy\tbut not a bad boy")# \t gives a tab space after it
print("Harry is a good boy but not a \"bad boy\"")# \" for adding " " inside the string
print('Harry is a good boy but not a \'bad boy\'')# \' for adding ' ' inside the string